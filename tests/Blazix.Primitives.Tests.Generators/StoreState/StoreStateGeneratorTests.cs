    [Fact]
    [Trait("Requirement", "UTL-STA-11")]
    public async Task Generates_into_a_generic_record_nested_in_partial_types_and_the_global_namespace()
    {
        // A member typed by a type parameter is compared through Equality.Is: how it compares is known only at instantiation.
        const string source = """
            #nullable enable
            using Blazix.Primitives.Store;

            public static partial class Outer
            {
                public partial class Inner
                {
                    [StoreState]
                    public sealed partial record ValueStoreState<TValue>(TValue Value, bool Open) : IStoreState<ValueStoreState<TValue>>;
                }
            }
            """;

        const string expected = """
            // <auto-generated/>
            // Copy and ShallowEquals of Outer.Inner.ValueStoreState<TValue> for its store, emitted by Blazix.Primitives.Generators.
            #nullable enable

            partial class Outer
            {
                partial class Inner
                {
                    partial record ValueStoreState<TValue>
                    {
                        /// <inheritdoc />
                        public static global::Outer.Inner.ValueStoreState<TValue> Copy(global::Outer.Inner.ValueStoreState<TValue> state) => state with { };

                        /// <inheritdoc />
                        public static bool ShallowEquals(global::Outer.Inner.ValueStoreState<TValue> left, global::Outer.Inner.ValueStoreState<TValue> right) =>
                            global::Blazix.Primitives.Store.Equality.Is(left.Value, right.Value)
                            && left.Open == right.Open;
                    }
                }
            }

            """;

        await RunAsync(source, ("Outer.Inner.ValueStoreState{TValue}.StoreState.g.cs", expected));
    }

