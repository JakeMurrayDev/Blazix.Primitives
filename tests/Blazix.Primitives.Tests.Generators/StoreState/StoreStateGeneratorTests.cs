    [Fact]
    [Trait("Requirement", "UTL-STA-11")]
    [Trait("Requirement", "UTL-STA-12")]
    public async Task Compares_every_member_in_declaration_order_by_the_store_equality_and_skips_a_computed_property()
    {
        // Each comparison is written for the member's type, never through a generic call: == for a bool, an enum or a
        // nullable int; string.Equals for a string; ReferenceEquals for a record or a store, never structurally.
        const string source = """
            #nullable enable
            using Blazix.Primitives.Store;

            namespace Probe;

            public enum Orientation { Horizontal, Vertical }

            public sealed record Anchor(double X, double Y);

            [StoreState]
            public sealed partial record SliderStoreState(
                bool Dragging,
                Orientation Orientation,
                string? Label,
                int? ActiveThumb,
                Anchor Anchor,
                Store<SliderStoreState>? Parent) : IStoreState<SliderStoreState>
            {
                public bool Vertical => Orientation == Orientation.Vertical;
            }
            """;

        const string expected = """
            // <auto-generated/>
            // Copy and ShallowEquals of Probe.SliderStoreState for its store, emitted by Blazix.Primitives.Generators.
            #nullable enable

            namespace Probe;

            partial record SliderStoreState
            {
                /// <inheritdoc />
                public static global::Probe.SliderStoreState Copy(global::Probe.SliderStoreState state) => state with { };

                /// <inheritdoc />
                public static bool ShallowEquals(global::Probe.SliderStoreState left, global::Probe.SliderStoreState right) =>
                    left.Dragging == right.Dragging
                    && left.Orientation == right.Orientation
                    && string.Equals(left.Label, right.Label)
                    && left.ActiveThumb == right.ActiveThumb
                    && object.ReferenceEquals(left.Anchor, right.Anchor)
                    && object.ReferenceEquals(left.Parent, right.Parent);
            }

            """;

        await RunAsync(source, ("Probe.SliderStoreState.StoreState.g.cs", expected));
    }

    [Fact]
    [Trait("Requirement", "UTL-STA-11")]
    public async Task Compares_init_only_get_only_non_public_and_field_members_and_skips_static_ones()
    {
        // Every instance member `with` copies takes part: init-only and get-only auto-properties through the property,
        // whatever their accessibility, and fields directly (a hand-written property over a field through the field).
        // Static and constant members hold no per-record value.
        const string source = """
            #nullable enable
            using Blazix.Primitives.Store;

            namespace Probe;

            [StoreState]
            public sealed partial record PopupStoreState(bool Open) : IStoreState<PopupStoreState>
            {
