    // The generated source of a record whose only member is `bool Open`.
    private static string OpenOnly(string ns, string name) => $$"""
        // <auto-generated/>
        // Copy and ShallowEquals of {{ns}}.{{name}} for its store, emitted by Blazix.Primitives.Generators.
        #nullable enable

        namespace {{ns}};

        partial record {{name}}
        {
            /// <inheritdoc />
            public static global::{{ns}}.{{name}} Copy(global::{{ns}}.{{name}} state) => state with { };

            /// <inheritdoc />
            public static bool ShallowEquals(global::{{ns}}.{{name}} left, global::{{ns}}.{{name}} right) =>
                left.Open == right.Open;
        }

        """;

    private static async Task RunAsync(string source, params (string HintName, string Content)[] generated)
    {
        CSharpSourceGeneratorTest<StoreStateGenerator, DefaultVerifier> test = new()
        {
            ReferenceAssemblies = ReferenceAssemblies.Net.Net100,
        };
        test.TestState.Sources.Add(("Shims.cs", LibraryShims.Source));
        test.TestState.Sources.Add(("Input.cs", source));
        foreach ((string hintName, string content) in generated)
        {
            test.TestState.GeneratedSources.Add((typeof(StoreStateGenerator), hintName, SourceText.From(content, Encoding.UTF8)));
        }

        await test.RunAsync(TestContext.Current.CancellationToken);
    }
