                private const int Limit = 3;

                private readonly long stamp;

                public string? ActiveId { get; init; }

                internal int Depth { get; init; }

                public double? Ratio;

                public long Stamp
                {
                    get => stamp;
                    init => stamp = value;
                }

                public static int Created { get; set; }

                public int Count { get; } = Limit;

                public string Summary => Open ? "open" : "closed";
            }
            """;

        const string expected = """
            // <auto-generated/>
            // Copy and ShallowEquals of Probe.PopupStoreState for its store, emitted by Blazix.Primitives.Generators.
            #nullable enable

            namespace Probe;

            partial record PopupStoreState
            {
                /// <inheritdoc />
                public static global::Probe.PopupStoreState Copy(global::Probe.PopupStoreState state) => state with { };

                /// <inheritdoc />
                public static bool ShallowEquals(global::Probe.PopupStoreState left, global::Probe.PopupStoreState right) =>
                    left.Open == right.Open
                    && left.stamp == right.stamp
                    && string.Equals(left.ActiveId, right.ActiveId)
                    && left.Depth == right.Depth
                    && (left.Ratio is { } leftRatio ? right.Ratio is { } rightRatio && (global::System.BitConverter.DoubleToInt64Bits(leftRatio) == global::System.BitConverter.DoubleToInt64Bits(rightRatio) || (double.IsNaN(leftRatio) && double.IsNaN(rightRatio))) : right.Ratio is null)
                    && left.Count == right.Count;
            }

            """;

        await RunAsync(source, ("Probe.PopupStoreState.StoreState.g.cs", expected));
    }

    [Fact]
    [Trait("Requirement", "UTL-STA-11")]
    public async Task Compares_floating_point_by_Object_is_and_other_value_types_by_their_operator_or_IEquatable()
    {
        // double, float and Half: identical bits or both NaN (Object.is), inlined. A struct with == (decimal, char, Guid,
        // a record struct; lifted for a nullable one) uses it; one with only IEquatable<T> (a tuple, Size) calls Equals.
        const string source = """
            #nullable enable
            using System;
            using Blazix.Primitives.Store;

            namespace Probe;

            public readonly struct Size : IEquatable<Size>
            {
                public Size(int width) => Width = width;

                public int Width { get; }

                public bool Equals(Size other) => Width == other.Width;

                public override bool Equals(object? obj) => obj is Size other && Equals(other);

                public override int GetHashCode() => Width;
            }

            public readonly record struct Span(int Start, int End);

            [StoreState]
            public sealed partial record MeasureStoreState(
                double Ratio,
                float Scale,
                Half Precision,
                decimal Amount,
                char Key,
                Guid Id,
                Guid? OwnerId,
                Span Selection,
                Size Size,
                Size? MaxSize,
                (int Row, int Column) Cell) : IStoreState<MeasureStoreState>;
            """;

        const string expected = """
            // <auto-generated/>
            // Copy and ShallowEquals of Probe.MeasureStoreState for its store, emitted by Blazix.Primitives.Generators.
            #nullable enable

            namespace Probe;

            partial record MeasureStoreState
            {
                /// <inheritdoc />
                public static global::Probe.MeasureStoreState Copy(global::Probe.MeasureStoreState state) => state with { };

                /// <inheritdoc />
                public static bool ShallowEquals(global::Probe.MeasureStoreState left, global::Probe.MeasureStoreState right) =>
                    (global::System.BitConverter.DoubleToInt64Bits(left.Ratio) == global::System.BitConverter.DoubleToInt64Bits(right.Ratio) || (double.IsNaN(left.Ratio) && double.IsNaN(right.Ratio)))
                    && (global::System.BitConverter.SingleToInt32Bits(left.Scale) == global::System.BitConverter.SingleToInt32Bits(right.Scale) || (float.IsNaN(left.Scale) && float.IsNaN(right.Scale)))
                    && (global::System.BitConverter.HalfToInt16Bits(left.Precision) == global::System.BitConverter.HalfToInt16Bits(right.Precision) || (global::System.Half.IsNaN(left.Precision) && global::System.Half.IsNaN(right.Precision)))
                    && left.Amount == right.Amount
                    && left.Key == right.Key
                    && left.Id == right.Id
                    && left.OwnerId == right.OwnerId
                    && left.Selection == right.Selection
                    && left.Size.Equals(right.Size)
                    && (left.MaxSize is { } leftMaxSize ? right.MaxSize is { } rightMaxSize && leftMaxSize.Equals(rightMaxSize) : right.MaxSize is null)
                    && left.Cell.Equals(right.Cell);
            }

            """;

        await RunAsync(source, ("Probe.MeasureStoreState.StoreState.g.cs", expected));
    }

