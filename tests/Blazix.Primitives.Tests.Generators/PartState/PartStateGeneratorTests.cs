    [Fact]
    [Trait("Requirement", "RND-ALG-07")]
    public async Task Projects_bool_enum_string_and_number_properties_in_declaration_order()
    {
        const string source = """
            #nullable enable
            using Blazix.Primitives.Rendering;

            namespace Probe;

            public enum Orientation { Horizontal, Vertical }

            public enum TransitionStatus { Starting, Ending, Idle, InlineStart }

            [PartState]
            public sealed partial record SwitchRootState(
                bool Checked,
                Orientation Orientation,
                string? Label,
                int Count,
                double Percentage,
                TransitionStatus? TransitionStatus,
                bool? ReadOnly,
                long? Index,
                char Key,
                decimal Amount);
            """;

        const string expected = """
            // <auto-generated/>
            // Projection of Probe.SwitchRootState to data-* attributes, emitted by Blazix.Primitives.Generators.
            #nullable enable

            namespace Probe;

            partial record SwitchRootState : global::Blazix.Primitives.Rendering.IPartState<global::Probe.SwitchRootState>
            {
                /// <inheritdoc />
                void global::Blazix.Primitives.Rendering.IPartState<global::Probe.SwitchRootState>.ProjectStateAttributes(global::Blazix.Primitives.Rendering.StateAttributesMapping<global::Probe.SwitchRootState>? mapping, global::Blazix.Primitives.Rendering.StateAttributeWriter writer)
                {
                    if (mapping is null || !mapping.TryProject("Checked", this.Checked, writer))
                    {
                        if (this.Checked)
                        {
                            writer.Set("data-checked", "");
                        }
                    }

                    if (mapping is null || !mapping.TryProject("Orientation", this.Orientation, writer))
                    {
                        string? value = this.Orientation switch
                        {
                            global::Probe.Orientation.Horizontal => "horizontal",
                            global::Probe.Orientation.Vertical => "vertical",
                            _ => null,
                        };
                        if (value is not null)
                        {
                            writer.Set("data-orientation", value);
                        }
                    }

                    if (mapping is null || !mapping.TryProject("Label", this.Label, writer))
                    {
                        if (!string.IsNullOrEmpty(this.Label))
                        {
                            writer.Set("data-label", this.Label);
                        }
                    }

                    if (mapping is null || !mapping.TryProject("Count", this.Count, writer))
                    {
                        if (this.Count != 0)
                        {
                            writer.Set("data-count", this.Count.ToString(global::System.Globalization.CultureInfo.InvariantCulture));
                        }
                    }

                    if (mapping is null || !mapping.TryProject("Percentage", this.Percentage, writer))
                    {
                        if (this.Percentage != 0 && !double.IsNaN(this.Percentage))
                        {
                            writer.Set("data-percentage", this.Percentage.ToString(global::System.Globalization.CultureInfo.InvariantCulture));
                        }
                    }

                    if (mapping is null || !mapping.TryProject("TransitionStatus", this.TransitionStatus, writer))
                    {
                        if (this.TransitionStatus is global::Probe.TransitionStatus enumValue)
                        {
                            string? value = enumValue switch
                            {
                                global::Probe.TransitionStatus.Starting => "starting",
                                global::Probe.TransitionStatus.Ending => "ending",
                                global::Probe.TransitionStatus.Idle => "idle",
                                global::Probe.TransitionStatus.InlineStart => "inline-start",
                                _ => null,
                            };
                            if (value is not null)
                            {
                                writer.Set("data-transitionstatus", value);
                            }
                        }
                    }

                    if (mapping is null || !mapping.TryProject("ReadOnly", this.ReadOnly, writer))
                    {
                        if (this.ReadOnly == true)
                        {
                            writer.Set("data-readonly", "");
                        }
                    }

                    if (mapping is null || !mapping.TryProject("Index", this.Index, writer))
                    {
                        if (this.Index is { } value && value != 0)
                        {
                            writer.Set("data-index", value.ToString(global::System.Globalization.CultureInfo.InvariantCulture));
                        }
                    }

                    if (mapping is null || !mapping.TryProject("Key", this.Key, writer))
                    {
                        if (this.Key != '\0')
                        {
                            writer.Set("data-key", this.Key.ToString());
                        }
                    }

                    if (mapping is null || !mapping.TryProject("Amount", this.Amount, writer))
                    {
                        if (this.Amount != 0)
                        {
                            writer.Set("data-amount", this.Amount.ToString(global::System.Globalization.CultureInfo.InvariantCulture));
                        }
                    }
                }
            }

            """;

        await RunAsync(source, ("Probe.SwitchRootState.PartState.g.cs", expected));
    }

